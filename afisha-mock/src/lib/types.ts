/**
 * Единая модель события Афиши.
 *
 * Это «контракт» данных, который мини-Афиша отдаёт по API (GET /api/event/[id]),
 * а генератор открыток потребляет. В реальном внедрении этот же контракт
 * заполнялся бы внутренним API Афиши — здесь его наполняет парсер.
 */
export interface AfishaEvent {
  /** Числовой ID события из URL (например, 1003341). Уникален, используется в роутах. */
  id: string;
  /** Человекочитаемый slug из URL (pobeg-iz-volshebnogo-izmereniya). */
  slug: string;
  /** Исходная ссылка на afisha.ru, с которой спарсено событие. */
  sourceUrl: string;
  /** Раздел Афиши: movie | concert | theatre | exhibition | ... (из пути URL). */
  category: string;

  /** Название события (RU). */
  title: string;
  /** Оригинальное название, если есть (для фильмов/концертов). */
  originalTitle?: string;
  /** Постер / главное изображение. */
  image?: string;
  /** Описание / синопсис. */
  description?: string;

  /** Жанры / теги. */
  genres?: string[];
  /** Дата события или начала проката (ISO или как на сайте). */
  date?: string;
  /** Страна (для фильмов). */
  country?: string;
  /** Длительность (как на сайте, напр. "1 ч 53 мин"). */
  duration?: string;
  /** Возрастной рейтинг, напр. "6+". */
  ageRating?: string;
  /** Режиссёр / автор / организатор. */
  director?: string;
  /** Площадка / место проведения. */
  venue?: string;
  /** Цена / диапазон цен, напр. "от 850 ₽". */
  price?: string;
  /** Рейтинг события, если указан. */
  rating?: string;

  /** Когда событие было спарсено (ISO-время). */
  parsedAt: string;
}
